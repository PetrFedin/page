#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {demoFashionRows,parseFashionCsv,fashionCsv,fashionTemplate,buildFashionReport,validateFashionRows,FASHION_ROLES} from '../assets/fashion-analytics-core.js';

const demo=demoFashionRows();
const valid=validateFashionRows(demo);
assert.equal(valid.ok,true,valid.errors.join('; '));
assert.equal(demo.length,24,'Six SKU scenarios over four months');
assert.ok(Object.keys(FASHION_ROLES).length>=4);
const report=buildFashionReport(demo,{role:'department',view:'budget',groupBy:'brand'});
assert.equal(report.ok,true);
assert.equal(report.rows.length,3);
assert.equal(report.months.length,4);
assert.equal(report.latestMonth,'2026-09');
assert.equal(report.trend.length,4);
assert.equal(report.totals.otb,report.totals.purchaseBudget-report.totals.receiptsCost-report.totals.openPOCost);
assert.equal(report.totals.netUnits,report.totals.soldUnits-report.totals.returnedUnits);
assert.equal(report.totals.grossProfit,report.totals.netSales-report.totals.cogs);
assert.ok(report.totals.sellThrough>0&&report.totals.sellThrough<=1);
assert.ok(report.totals.gmroi>0);
assert.ok(report.totals.wos>=0);
assert.ok(report.totals.forecast>=0);
const forecast=buildFashionReport(demo,{role:'brand',view:'forecast',growthPct:15});
assert.ok(forecast.totals.forecast>=report.totals.forecast);
const csv=fashionCsv(demo);
const parsed=parseFashionCsv(csv);
assert.equal(parsed.ok,true,parsed.errors.join('; '));
assert.equal(parsed.rows.length,demo.length);
assert.equal(parseFashionCsv(fashionTemplate()).ok,true);
assert.equal(parseFashionCsv('period;sku\n2026-09;x').ok,false);
const bad=demo.map(x=>({...x}));bad[0].closing_units+=1;
assert.ok(validateFashionRows(bad).errors.some(e=>e.includes('reconcile')));
const missing=demo.map(x=>({...x}));missing[0].net_sales=-3;
assert.equal(validateFashionRows(missing).ok,false);
const duplicate=demo.concat({...demo[0]});
assert.ok(validateFashionRows(duplicate).errors.some(e=>e.includes('duplicated')));
const aging=demo.map(x=>({...x}));aging[0].aged_90_cost=aging[0].closing_stock_cost+100;
assert.equal(validateFashionRows(aging).ok,false);
const sparse=demo.filter(r=>r.period==='2026-09');
assert.equal(buildFashionReport(sparse).totals.forecast,null,'No misleading forecast for one month');
const originalPeriod=demo.find(x=>x.period==='2026-06');
const periodLatest=report.totals.closingCost;
assert.notEqual(periodLatest,demo.reduce((a,b)=>a+b.closing_stock_cost,0),
  'Stock must not be summed across periods');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const en=readFileSync(new URL('../en/index.html',import.meta.url),'utf8');
const app=readFileSync(new URL('../assets/app.js',import.meta.url),'utf8');
for(const page of [html,en])assert.ok(page.includes('id="fashion-analytics"'));
for(const page of [html,en])assert.ok(page.includes('analytics.html'));
assert.ok(!app.includes("mountFashionAnalytics($('#fashion-analytics'),lang)"),'Landing must not mount synthetic demo figures');
console.log('PASS: Fashion Analytics roles, period snapshot, budgets, flow reconciliation, GMROI, WOS, forecasting, CSV parsing and demo boundaries.');
