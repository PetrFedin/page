import assert from 'node:assert/strict';
import {demoFashionRows} from '../assets/fashion-analytics-core.js';
import {analyzeFashionAssortment} from '../assets/fashion-assortment.js';
const rows=demoFashionRows();
const x=analyzeFashionAssortment(rows,{dimension:'category',leadWeeks:4,safetyWeeks:2});
assert.equal(x.ok,true);assert.ok(x.groups.length>=4);assert.ok(x.groups.every(g=>['A','B','C'].includes(g.abc)));
assert.ok(x.groups.every(g=>['X','Y','Z'].includes(g.xyz)));
assert.ok(x.groups.every(g=>g.suggestedUnits===null||g.suggestedUnits>=0));
assert.ok(x.groups.every(g=>g.suggestedCost===null||g.suggestedCost>=0));
assert.ok(Math.abs(x.groups.reduce((a,g)=>a+(g.revenueShare||0),0)-1)<1e-9);
const one=analyzeFashionAssortment(rows.filter(r=>r.period==='2026-09'));
assert.ok(one.groups.every(g=>g.xyz==='N/A'));
const longer=analyzeFashionAssortment(rows,{leadWeeks:12,safetyWeeks:2});
for(let i=0;i<x.groups.length;i++)assert.ok(longer.groups[i].suggestedUnits>=x.groups[i].suggestedUnits);
const zero=analyzeFashionAssortment(rows,{leadWeeks:0,safetyWeeks:0});
assert.ok(zero.groups.every(g=>g.suggestedUnits===0));
assert.throws(()=>analyzeFashionAssortment(rows,{leadWeeks:-1}),RangeError);
const c=analyzeFashionAssortment(rows,{budgetLimit:0});
assert.equal(c.budgetWarning,c.needsBudget>0);
console.log('PASS Fashion assortment ABC/XYZ, insufficient history, budget warning and replenishment sensitivity');
