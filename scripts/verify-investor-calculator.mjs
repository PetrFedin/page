#!/usr/bin/env node
import assert from 'node:assert/strict';
import {calculateForecast, runScenarios, validateAssumptions, capitalSensitivity} from '../assets/investor-calculator.js';
const a={leads:10,conversion:10,churn:0,starting:0,price:100,variable:20,fixed:40,launch:50,opening:0,reserve:0,months:12,spread:20};
assert.equal(validateAssumptions(a),true);
const base=calculateForecast(a);
assert.equal(base.rows.length,13);
assert.equal(base.rows[0].cash,-50);
assert.equal(base.rows[1].customers,1);
assert.equal(base.rows[1].operating,40);
assert.equal(base.rows[1].cash,-10);
assert.equal(base.rows[2].cash,110);
assert.equal(base.capitalRequired,50);
assert.equal(base.requiredCustomers,1);
assert.equal(base.stableMonth,1);
assert.equal(base.rows[12].customers,12);
const sc=runScenarios(a);
assert.ok(sc.conservative.rows[1].customers<base.rows[1].customers);
assert.ok(sc.optimistic.rows[1].customers>base.rows[1].customers);
assert.ok(sc.conservative.capitalRequired>=base.capitalRequired);
assert.equal(capitalSensitivity(a).length,4);
const loss=calculateForecast({...a,price:10,variable:20});
assert.equal(loss.requiredCustomers,null);
assert.equal(loss.stableMonth,null);
assert.ok(loss.capitalRequired>base.capitalRequired);
const noSpend=calculateForecast({...a,leads:0,conversion:0,starting:0,price:0,variable:0,fixed:0,launch:0});
assert.equal(noSpend.capitalRequired,0);
assert.equal(noSpend.stableMonth,1);
assert.equal(noSpend.requiredCustomers,0);
assert.equal(validateAssumptions({...a,churn:101}),false);
assert.equal(validateAssumptions({...a,conversion:-5}),false);
assert.equal(validateAssumptions({...a,months:13}),false);
assert.throws(()=>calculateForecast({...a,spread:75}),RangeError);
console.log('PASS: capital peak, break-even, scenario direction, churn/range validation, no-contribution edge cases');
