function renderSection(section) {
  const rowsHtml = section.rows.map(([feature, syntha]) => `
    <tr>
      <th scope="row">${feature}</th>
      <td class="us">${syntha}</td>
      ${COMPETITORS.map(() => `<td class="todo">${TODO}</td>`).join('')}
    </tr>`).join('');

  return `
    <details class="cmp-section" id="${section.id}">
      <summary>
        <h3>${section.title}</h3>
        <span class="cmp-arrow" aria-hidden="true">+</span>
      </summary>
      <p class="cmp-desc">${section.desc}</p>
      <div class="cmp-wrap">
        <table class="cmp">
          <thead>
            <tr>
              <th scope="col">Функция</th>
              <th scope="col" class="us">Syntha</th>
              ${COMPETITORS.map((c) => `<th scope="col">${c}</th>`).join('')}
            </tr>
          </thead>
          <tbody>${rowsHtml}</tbody>
        </table>
      </div>
    </details>`;
}

document.getElementById('cmp-root').innerHTML = SECTIONS.map(renderSection).join('');

/* Раздел из ссылки (#orders и т.п.) открывается сразу и прокручивается в вид. */
if (location.hash) {
  const target = document.querySelector(location.hash);
  if (target) {
    target.open = true;
    requestAnimationFrame(() => target.scrollIntoView({ block: 'start' }));
  }
}
